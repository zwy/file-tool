"""片头广告识别与裁剪。

这个包解决的是一件很具体的事：**视频开头插了一段广告，要把它切掉**。

## 为什么可以「抛开人工」

实测本库的 276 个视频后，事实是：

- 片头广告**不是每个视频各不相同**。同一支广告素材被反复插在几十个不同
  番号的视频前面 —— 例如 ``26.716383, 26.74975, 30.276026`` 这一串场景切换
  时间戳，同时出现在 ABF-094、ACHJ-038、AIAV-003、AV-174、CAWD-660 等
  十几个毫不相关的作品里，**毫秒级一致**。
- 同一个广告在不同视频里被**重新编码**过。逐像素 md5 对不上（FamilyA 的
  首帧哈希就不同），但感知哈希（dHash）下同族视频的连续匹配前缀长达
  27~45 秒，跨族视频的覆盖率是 0.00 —— 完全可分。

所以「识别」不是机器学习问题，是**指纹检索**问题：把见过的广告存成模板，
新视频来了先算指纹再对模板库检索，命中就裁。

## 三层结构

1. **指纹层**（:mod:`file_tool.adcut.fingerprint`）
   把片头压成一串 64 位感知哈希 + 一条帧间差异曲线。纯 Python 实现，
   不依赖 PIL / numpy —— 帧数据由 ffmpeg 以 rawvideo 管道吐出来。

2. **模板层**（:mod:`file_tool.adcut.templates`）
   YAML 模板库（与 ``rules/numbering.yaml`` 同构）。每个模板存一支广告的
   指纹序列，外加负样本库（人眼判定「这里没有广告」的片段）。

3. **决策层**（:mod:`file_tool.adcut.detect` / :mod:`file_tool.adcut.cut`）
   匹配 + 打分 → 裁剪点 → 临时文件 → 校验 → 原子替换。

## 人在哪里

人工只做一件事：**给一个没见过的广告划一刀**（``ad-cut learn``）。
划完之后，这一支广告的所有同族视频自动命中；再遇到新广告，再划一刀。
这是「从 0 开始慢慢越来越快」的具体含义 —— 人工量正比于**广告种类数**，
而不是视频数。
"""
